/** The Material 3 theme, light or dark as the system is. */
@Composable
fun WeatherTheme(
    dark: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    MaterialTheme(colorScheme = if (dark) darkColors else lightColors, content = content)
}

